import { expect, test } from './authenticated';

test('studio research and manual notebook workflow persist against the actual API', async ({ page }) => {
  const title = `Evergreen studio ${Date.now()}`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Centro de producción', exact: true }).click();
  await page.getByRole('button', { name: 'Temas', exact: true }).click();
  await page.getByLabel('Título del tema').fill(title);
  await page.getByLabel('Evaluación evergreen').fill('Evergreen assessment written by the operator; no fabricated metrics.');
  await page.getByRole('button', { name: 'Registrar tema', exact: true }).click();
  const topic = page.getByRole('listitem').filter({ has: page.getByText(title, { exact: true }) });
  await topic.getByRole('button', { name: 'Aprobar', exact: true }).click();
  await topic.getByRole('button', { name: 'Crear producción del tema', exact: true }).click();
  await topic.getByRole('button', { name: 'Abrir producción del tema', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.getByLabel('Tipo de fuente').selectOption('Note');
  await page.getByLabel('Título de la fuente').fill('Operator notes');
  await page.getByLabel('Notas o texto de la fuente').fill('Original research note for this controlled test.');
  await page.getByLabel('Procedencia y autorización', { exact: true }).fill('Authored specifically for this test.');
  await page.getByRole('button', { name: 'Registrar fuente', exact: true }).click();
  await expect(page.getByText('Operator notes', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Congelar paquete y preparar tareas', exact: true }).click();
  await page.locator('summary').filter({ hasText: 'Paquete v1' }).click();
  await expect(page.getByRole('link', { name: 'Descargar paquete', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'NotebookLM', exact: true }).click();
  await page.getByLabel('URL del notebook dedicado').fill('https://notebooklm.google.com/notebook/controlled-manual-reference');
  await page.getByRole('button', { name: 'Registrar notebook', exact: true }).click();
  await page.getByLabel('Evidencia de la tarea manual').fill('Controlled attestation of a reference; not live provider verification.');
  await page.getByLabel('Declaro que he realizado la operación en la interfaz oficial', { exact: true }).check();
  await page.getByRole('button', { name: 'Registrar declaración: CreateNotebook', exact: true }).click();
  await expect(page.locator('summary').filter({ hasText: 'Crear cuaderno' })).toContainText('Completada');
  await page.getByRole('button', { name: 'Vídeo y calidad', exact: true }).click();
  await page.getByRole('button', { name: 'Comprobar calidad', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Existen bloqueos', exact: true })).toBeVisible();
  await expect(page.getByText('Falta un vídeo canónico válido de NotebookLM.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Publicación', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Aprobar y encolar subida a YouTube', exact: true })).toBeDisabled();
  await page.getByLabel('Descripción y créditos', { exact: true }).fill('Controlled local metadata; no real upload is authorized.');
  await page.getByLabel('¿Contenido dirigido a menores?').selectOption('false');
  await page.getByLabel('Visibilidad tras subir').selectOption('private');
  const schedule = page.getByLabel('Publicación pública futura (UTC; requiere public; vacía para no programar)', { exact: true });
  await schedule.fill('2027-01-05T12:00');
  await page.getByRole('button', { name: 'Guardar metadatos de publicación', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Selecciona public expresamente');
  await schedule.fill('');
  await page.getByRole('button', { name: 'Guardar metadatos de publicación', exact: true }).click();
  await expect(page.getByText('Operación guardada.', { exact: true })).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await expect(schedule).toHaveValue('');
  await expect(page.getByLabel('Visibilidad tras subir')).toHaveValue('private');
  await page.getByRole('button', { name: 'Vídeo y calidad', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Existen bloqueos', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Comprobar calidad', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Existen bloqueos', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Historial', exact: true }).click();
  await expect(page.getByText('SourcePackageFrozen', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/studio-mobile.png', fullPage: true });
});
