import { expect, test } from './authenticated';

test('operator completes the Phase 1 workflow against the actual API', async ({ page }) => {
  const topic = `E2E ${Date.now()}`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Semana editorial', exact: true }).click();
  await page.getByLabel('Nombre del canal').fill('Local editorial');
  await page.getByLabel('Zona horaria IANA').fill('Europe/Madrid');
  await page.getByRole('button', { name: 'Guardar canal e inicializar semana' }).click();
  await expect(page.getByRole('form')).toHaveCount(7);
  const monday = page.getByRole('form', { name: 'Configuración Lunes' });
  await monday.getByLabel('Nombre del nicho').fill('Evergreen history');
  await monday.getByLabel('Descripción').fill('Historical context');
  await monday.getByLabel('Guía editorial').fill('Use verified sources');
  await monday.getByLabel('Habilitar para nuevas producciones').check();
  await monday.getByRole('button', { name: 'Guardar Lunes' }).click();
  await expect(page.getByRole('status')).toHaveText('Cambios guardados.');
  await page.getByRole('button', { name: 'Producciones', exact: true }).click();
  await page.getByLabel('Tema de trabajo').fill(topic);
  await page.getByLabel('Fecha prevista').fill('2026-11-02');
  await page.getByRole('button', { name: 'Crear producción' }).click();
  await expect(page.getByLabel('Tema de la producción')).toHaveValue(topic);
  await page.getByLabel('Tema de la producción').fill(topic + ' edited');
  await page.getByLabel('Fecha de publicación').fill('2026-11-03');
  await page.getByRole('button', { name: 'Guardar producción' }).click();
  await expect(page.getByRole('button', { name: topic + ' edited', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'BriefReady', exact: true }).click();
  await expect(page.getByText('Siguiente acción: Preparar NotebookLM manualmente')).toBeVisible();
  await page.getByLabel('URL del notebook').fill('https://evil.example/notebook/id');
  await page.getByRole('button', { name: 'Guardar referencia' }).click();
  await expect(page.getByRole('alert')).toContainText('valid HTTPS');
  await page.getByLabel('URL del notebook').fill('https://notebooklm.google.com/notebook/e2e-reference');
  await page.getByRole('button', { name: 'Guardar referencia' }).click();
  await expect(page.getByRole('link', { name: 'Abrir notebook registrado' })).toHaveAttribute('href', 'https://notebooklm.google.com/notebook/e2e-reference');
  await page.getByRole('button', { name: 'AwaitingNotebook', exact: true }).click();
  await expect(page.getByText('Siguiente acción: Registrar o revisar el notebook')).toBeVisible();
  await page.getByRole('button', { name: 'Blocked', exact: true }).click();
  await expect(page.getByText('Siguiente acción: Resolver bloqueo')).toBeVisible();
  await page.getByRole('button', { name: 'Cancelled', exact: true }).click();
  await expect(page.getByLabel('Tema de la producción')).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Guardar referencia' })).toBeDisabled();
  await page.getByLabel('Filtrar por estado').selectOption('Draft');
  await expect(page.getByRole('button', { name: topic + ' edited', exact: true })).toHaveCount(0);
  await page.getByLabel('Filtrar por estado').selectOption('Cancelled');
  await expect(page.getByRole('button', { name: topic + ' edited', exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Producciones', exact: true }).click();
  await page.getByRole('button', { name: topic + ' edited', exact: true }).click();
  await expect(page.getByRole('listitem').filter({ hasText: 'BriefReady' }).first()).toBeVisible();
  await expect(page.getByRole('link', { name: 'Abrir notebook registrado' })).toBeVisible();
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Semana editorial' }).focus();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: 'Integraciones', exact: true })).toBeFocused();
});

test('niche disabling preserves history and failed loading can recover', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Semana editorial', exact: true }).click();
  const monday = page.getByRole('form', { name: 'Configuración Lunes' });
  await monday.getByLabel('Nombre del nicho').fill('Evergreen history');
  await monday.getByLabel('Habilitar para nuevas producciones').uncheck();
  await monday.getByRole('button', { name: 'Guardar Lunes' }).click();
  await expect(monday.getByText('Desactivado', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Producciones', exact: true }).click();
  await expect(page.getByLabel('Nicho para nueva producción').getByRole('option', { name: 'Evergreen history' })).toHaveCount(0);
  await expect(page.getByLabel('Filtrar por nicho').getByRole('option', { name: 'Evergreen history (desactivado)' })).toHaveCount(1);
  await page.getByRole('button', { name: 'Semana editorial' }).click();
  await monday.getByLabel('Habilitar para nuevas producciones').check();
  await monday.getByRole('button', { name: 'Guardar Lunes' }).click();
  await expect(page.getByRole('status')).toHaveText('Cambios guardados.');
  await page.route('**/api/channel', route => route.fulfill({ status: 503, body: JSON.stringify({ detail: 'Service unavailable' }), contentType: 'application/problem+json' }));
  await page.reload();
  await expect(page.getByRole('alert')).toContainText('Service unavailable');
  await page.unroute('**/api/channel');
  await page.getByRole('button', { name: 'Reintentar carga' }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.getByRole('button', { name: 'Semana editorial', exact: true }).click();
  await expect(page.getByLabel('Nombre del canal')).toHaveValue('Local editorial');
});
