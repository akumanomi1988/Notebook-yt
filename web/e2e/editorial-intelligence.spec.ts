import { mkdirSync } from 'node:fs';
import { expect, test } from './local';
import { prepareEditorial } from './editorial-support';

test('editorial direction saves, validates, freezes and resumes in the local UI', async ({ page, request }) => {
  await request.put('/api/channel', { data: { name: 'NewSphere acceptance', timeZone: 'Europe/Madrid' } });
  const week = await (await request.get('/api/week')).json();
  const title = `Editorial direction acceptance ${Date.now()}`;
  const created = await request.post('/api/productions', { data: { contentNicheId: week[0].id, topic: title, plannedDate: '2027-01-05' } });
  expect(created.status()).toBe(201); const production = await created.json();
  const source = await request.post(`/api/studio/productions/${production.id}/sources`, { data: { title: 'Research fixture notes', kind: 'Note', url: '', notes: 'Controlled source for application behavior; not factual provider acceptance.', classification: 'Primary', provenance: 'Test author', included: true, artifactId: null } });
  expect(source.ok()).toBe(true);
  await page.goto('/'); await page.getByRole('button', { name: 'Centro de producción', exact: true }).click();
  await page.getByRole('button', { name: 'Espacios de trabajo', exact: true }).click();
  await page.getByRole('button', { name: title, exact: true }).click();
  await prepareEditorial(page, 'Research fixture notes');
  await page.getByRole('button', { name: 'Configuración NotebookLM', exact: true }).click();
  await page.getByLabel('Formato de Video Overview').selectOption('CINEMATIC');
  await expect(page.getByRole('alert')).toContainText('Cinematic requiere inglés');
  await expect(page.getByRole('button', { name: 'Guardar dirección editorial', exact: true })).toBeDisabled();
  await page.getByLabel('Formato de Video Overview').selectOption('EXPLAINER');
  await page.getByRole('button', { name: 'Guardar dirección editorial', exact: true }).click();
  await expect(page.getByText('Dirección editorial guardada.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Fuentes y paquete', exact: true }).click();
  await page.getByRole('button', { name: 'Aprobar paquete editorial', exact: true }).click();
  await expect(page.getByText('Paquete aprobado e inmutable', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Tema y enfoque', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Pregunta central', exact: true })).toBeDisabled();
  mkdirSync('../.impeccable/review', { recursive: true });
  await page.screenshot({ path: '../.impeccable/review/editorial-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../.impeccable/review/editorial-mobile.png', fullPage: true });
  await page.keyboard.press('Tab'); expect(await page.evaluate(() => document.activeElement?.tagName)).not.toBe('BODY');
  const preview = await (await request.get(`/api/studio/editorial/productions/${production.id}`)).json();
  expect(preview.frozen).toBe(true); expect(preview.sources).toHaveLength(1);
  expect(preview.effective.format).toBe('EXPLAINER'); expect(preview.effective.language).toBe('es-ES');
  const download = await request.get(`/api/studio/editorial/productions/${production.id}/export`);
  expect(await download.text()).toContain('Research fixture notes');
  const blocked = await request.post(`/api/studio/productions/${production.id}/upload`, { data: { approved: true, evidence: 'No video imported; must be blocked.' } });
  expect(blocked.status()).toBe(409);
});
