import { mkdirSync } from 'node:fs';
import { expect, test } from './local';

test('daily workspace navigation, grouped configuration and mobile layout are usable', async ({ page, request }) => {
  const title = `Demostración local: preparar el siguiente vídeo ${Date.now()}`;
  await request.put('/api/channel', { data: { name: 'NewSphere · entorno de pruebas', timeZone: 'Europe/Madrid' } });
  const names = ['Ciencia y espacio', 'Tecnología', 'Historia', 'Naturaleza', 'Aprendizaje', 'Geografía', 'Ingeniería'];
  for (let i = 0; i < 7; i++) await request.put(`/api/week/${i + 1}`, { data: { name: names[i], description: 'Configuración del entorno E2E aislado.', guidance: 'Consultar fuentes primarias y verificar afirmaciones.', enabled: true } });
  const week = await (await request.get('/api/week')).json();
  const created = await request.post('/api/productions', { data: { contentNicheId: week[0].id, topic: title, plannedDate: '2027-01-10' } });
  const production = await created.json();
  await request.post(`/api/studio/productions/${production.id}/open`);
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Tu mesa editorial' })).toBeVisible();
  await expect(page.locator('.readiness-strip')).toBeHidden();
  await expect(page.getByText(title, { exact: true })).toBeVisible();
  expect(await page.getByRole('navigation', { name: 'Módulos de producción' }).count()).toBe(0);
  mkdirSync('../.impeccable/review', { recursive: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '../.impeccable/review/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 1005, height: 1318 });
  await expect(page.locator('.readiness-strip')).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '../.impeccable/review/user-1005.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  const readinessBounds = await page.locator('.readiness-strip').boundingBox();
  expect(readinessBounds!.y + readinessBounds!.height).toBeLessThan(844);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../.impeccable/review/mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click();
  await expect(page.getByLabel('Idioma principal')).toBeVisible();
  const quality = page.locator('details').filter({ has: page.locator('summary').getByText('Calidad y almacenamiento', { exact: true }) });
  await expect(quality).not.toHaveAttribute('open');
  await quality.locator('summary').click();
  await expect(page.getByLabel('Altura mínima del vídeo (píxeles)')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '../.impeccable/review/settings-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Integraciones', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Conexiones oficiales' })).toBeVisible();
});
